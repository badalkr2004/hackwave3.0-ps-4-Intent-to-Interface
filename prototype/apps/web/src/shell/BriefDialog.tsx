import { useEffect, useRef, useState } from 'react';
import { Check, Copy, Download, FileText, Printer, X } from 'lucide-react';
import { MANIFESTS_BY_ID, type UISpec } from '@gestalt/shared';

export interface BriefDialogProps {
  spec: UISpec | null;
  open: boolean;
  onClose: () => void;
}

export function BriefDialog({ spec, open, onClose }: BriefDialogProps) {
  const ref = useRef<HTMLDialogElement>(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    const dialog = ref.current;
    if (!dialog) return;
    if (open && !dialog.open) dialog.showModal();
    if (!open && dialog.open) dialog.close();
  }, [open]);

  if (!spec) return null;

  const dateStr = new Date().toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });

  const panels = spec.panels;
  const receipts = spec.receipts;

  const markdownContent = [
    `# Executive Brief: ${spec.intent.headline}`,
    `Generated by Gestalt Adaptive Workspace · ${dateStr}`,
    '',
    `## Strategic Focus`,
    `- **Workflow Shape**: ${spec.intent.shape.toUpperCase()}`,
    spec.intent.scope.clientId
      ? `- **Client Context**: ${spec.intent.scope.clientId.toUpperCase()}`
      : '',
    `- **Active Panels Count**: ${panels.length}`,
    '',
    `## Questions Answered in this Interface`,
    ...panels.map((p) => {
      const m = MANIFESTS_BY_ID[p.componentId];
      return `- **${m?.title ?? p.componentId}**: ${m?.question ?? 'Operational metrics'}`;
    }),
    '',
    `## Auction Decisions & Evidence (Why Lens)`,
    ...receipts.map((r) => {
      const m = MANIFESTS_BY_ID[r.componentId];
      return `- **${m?.title ?? r.componentId}** (Score: ${Math.round(r.score * 100)}%): ${r.reason}`;
    }),
  ]
    .filter(Boolean)
    .join('\n');

  const onCopy = async () => {
    await navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const onDownload = () => {
    const blob = new Blob([markdownContent], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `executive-brief-${spec.intent.shape}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const onPrint = () => {
    window.print();
  };

  return (
    <dialog
      ref={ref}
      onClose={onClose}
      aria-labelledby="brief-dialog-title"
      className="m-auto w-[min(720px,calc(100vw-2rem))] rounded-lg border border-border bg-surface p-0 text-text shadow-panel backdrop:bg-bg/75"
    >
      <div className="flex items-center justify-between gap-4 border-b border-border px-5 py-3.5">
        <div className="flex items-center gap-2">
          <FileText className="size-4 text-accent" aria-hidden />
          <h2 id="brief-dialog-title" className="text-md font-medium text-text">
            Executive Workspace Brief
          </h2>
        </div>
        <button
          type="button"
          onClick={onClose}
          aria-label="Close brief"
          className="inline-flex size-8 items-center justify-center rounded-md text-muted hover:bg-surface-2 hover:text-text"
        >
          <X aria-hidden className="size-4" />
        </button>
      </div>

      <div className="max-h-[60vh] overflow-y-auto px-5 py-4 text-sm">
        <div className="rounded-md border border-border bg-bg/80 p-4 font-mono text-xs leading-relaxed text-text">
          <pre className="whitespace-pre-wrap">{markdownContent}</pre>
        </div>
      </div>

      <div className="flex flex-wrap items-center justify-between gap-2 border-t border-border px-5 py-3">
        <p className="text-xs text-muted">Includes current layout, questions answered, and Why Lens receipts.</p>
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={onPrint}
            className="inline-flex min-h-9 items-center gap-1.5 rounded-md border border-border px-3 text-xs font-medium text-text hover:bg-surface-2"
          >
            <Printer className="size-3.5" aria-hidden />
            Print
          </button>
          <button
            type="button"
            onClick={onDownload}
            className="inline-flex min-h-9 items-center gap-1.5 rounded-md border border-border px-3 text-xs font-medium text-text hover:bg-surface-2"
          >
            <Download className="size-3.5" aria-hidden />
            Save .md
          </button>
          <button
            type="button"
            onClick={() => void onCopy()}
            className="inline-flex min-h-9 items-center gap-1.5 rounded-md bg-accent px-3 text-xs font-medium text-on-accent transition-all duration-150 active:scale-95"
          >
            {copied ? <Check className="size-3.5 text-on-accent" /> : <Copy className="size-3.5" />}
            {copied ? 'Copied to clipboard' : 'Copy brief'}
          </button>
        </div>
      </div>
    </dialog>
  );
}
